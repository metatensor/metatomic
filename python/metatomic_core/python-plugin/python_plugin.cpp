/// `unload` callback for models loaded by this plugin
static mta_status_t python_model_unload(void* model_data) {
    auto gil = GilGuard();
    PY.Py_DecRef(static_cast<PyObject*>(model_data));
    return MTA_SUCCESS;
}

/// Check that `options_json` is NULL or an empty JSON object
static bool empty_options(const char* options_json) {
    if (options_json == nullptr) {
        return true;
    }

    auto options = std::string(options_json);
    auto is_space = [](char c) { return c == ' ' || c == '\t' || c == '\n' || c == '\r'; };

    auto compact = std::string();
    for (auto c: options) {
        if (!is_space(c)) {
            compact.push_back(c);
        }
    }
    return compact == "{}" || compact.empty();
}

/// Load the model defined in the script at `path`. This must be called with
/// the GIL held, and throws `PythonError` if a Python function fails.
static void load_python_model(const char* path, mta_model_t* model) {
    auto runpy = PyRef::check(PY.PyImport_ImportModule("runpy"));

    // the script is executed with `__name__ == "<run_path>"`
    auto globals = PyRef::check(PY.PyObject_CallMethod(runpy.get(), "run_path", "s", path));

    // borrowed reference, kept alive by `globals`
    auto* py_model = PY.PyDict_GetItemString(globals.get(), "model");
    if (py_model == nullptr) {
        throw PluginError(
            "the Python script at '" + std::string(path) +
            "' does not define a 'model' variable"
        );
    }

    auto metatomic = PyRef::check(PY.PyImport_ImportModule("metatomic"));
    auto base_model = PyRef::check(PY.PyObject_GetAttrString(metatomic.get(), "BaseModel"));
    auto external_model = PyRef::check(PY.PyObject_GetAttrString(metatomic.get(), "ExternalModel"));

    auto is_base = PY.PyObject_IsInstance(py_model, base_model.get());
    if (is_base < 0) {
        throw PythonError{};
    }

    auto is_external = PY.PyObject_IsInstance(py_model, external_model.get());
    if (is_external < 0) {
        throw PythonError{};
    }

    if ((is_base == 0) || (is_external != 0)) {
        throw PluginError(
            "the 'model' variable in the Python script at '" + std::string(path) +
            "' must be an instance of metatomic.BaseModel (and not metatomic.ExternalModel)"
        );
    }

    // Get the `mta_model_t` struct created by the Python code, and copy it in
    // the output. The function pointers in this struct are defined at the
    // module level in `metatomic._model._base`, and stay alive for as long as
    // this module is loaded, so we don't need to keep `raw_model` around.
    auto raw_model = PyRef::check(PY.PyObject_CallMethod(py_model, "_as_mta_model_t", nullptr));
    auto ctypes = PyRef::check(PY.PyImport_ImportModule("ctypes"));
    auto address = PyRef::check(PY.PyObject_CallMethod(ctypes.get(), "addressof", "O", raw_model.get()));

    auto* pointer = PY.PyLong_AsVoidPtr(address.get());
    if (pointer == nullptr) {
        if (PY.PyErr_Occurred() != nullptr) {
            throw PythonError{};
        }
        throw PluginError("got a NULL pointer for the model created by Python");
    }

    auto result = mta_model_t{};
    std::memcpy(&result, pointer, sizeof(mta_model_t));
    if (result.data != static_cast<void*>(py_model)) {
        throw PluginError("internal error: unexpected data pointer in the model created by Python");
    }

    // keep the model alive until `unload` is called
    PY.Py_IncRef(py_model);
    result.unload = python_model_unload;

    *model = result;
}

static mta_status_t load_model(const char* load_from, const char* options_json, mta_model_t* model) {
    try {
        if (load_from == nullptr || model == nullptr) {
            mta_set_last_error("got a NULL pointer in load_model", PLUGIN_NAME, nullptr, nullptr);
            return MTA_INVALID_PARAMETER_ERROR;
        }

        auto length = std::strlen(load_from);
        if (length < 3 || std::strcmp(load_from + length - 3, ".py") != 0) {
            // not a Python script, let other plugins try to load this model
            return MTA_UNSUPPORTED_MODEL_ERROR;
        }

        if (!empty_options(options_json)) {
            mta_set_last_error("the Python plugin does not support any options yet", PLUGIN_NAME, nullptr, nullptr);
            return MTA_INVALID_PARAMETER_ERROR;
        }

        ensure_python();

        auto gil = GilGuard();
        try {
            load_python_model(load_from, model);
        } catch (const PythonError&) {
            // this needs to run while we still hold the GIL
            return set_error_from_python();
        }

        return MTA_SUCCESS;
    } catch (const std::exception& e) {
        mta_set_last_error(e.what(), PLUGIN_NAME, nullptr, nullptr);
        return MTA_MODEL_ERROR;
    } catch (...) {
        mta_set_last_error("unknown C++ error in the Python plugin", PLUGIN_NAME, nullptr, nullptr);
        return MTA_MODEL_ERROR;
    }
}

MTA_REGISTER_PLUGIN(register_plugin, {
    mta_plugin_t plugin = {};
    plugin.abi_version = MTA_ABI_VERSION;
    plugin.name = PLUGIN_NAME;
    plugin.load_model = load_model;
    return register_plugin(plugin);
});
