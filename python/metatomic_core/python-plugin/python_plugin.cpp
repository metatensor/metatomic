// A metatomic plugin loading models defined in Python scripts.
//
// The script given to `mta_load_model` must define a `model` variable, which is
// an instance of `metatomic.BaseModel`.
//
// This plugin does not link to libpython. Instead, it uses the Python
// interpreter already running in the current process (if any), or finds the
// Python the user has active (`METATOMIC_PYTHON`, virtual environments, conda
// environments, or `PATH`), and starts it inside the current process. All the
// Python functions are found at runtime, so the same plugin works with all
// Python versions >= 3.10.
//
// Known limitations:
// - the engine and the Python package must use the same shared libmetatomic.
//   The Python package re-uses the libmetatomic already loaded in the process
//   if any, but this does not work if the engine links statically to metatomic;
// - if Python is already initialized in the process, we use it as-is, without
//   changing `sys.path`;

#if defined(__linux__) && !defined(_GNU_SOURCE)
// for RTLD_DEFAULT
#define _GNU_SOURCE
#endif

#include <cstddef>
#include <cstdio>
#include <cstdlib>
#include <cstring>

#include <mutex>
#include <optional>
#include <stdexcept>
#include <string>
#include <utility>
#include <vector>

