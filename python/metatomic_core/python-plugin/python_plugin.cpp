/// Check if libpython is already loaded in the current process, and get the
/// Python functions from there if it is.
static std::optional<PythonApi> find_python_in_process() {
#ifdef _WIN32
    auto modules = std::vector<HMODULE>(1024);
    DWORD needed = 0;
    auto process = GetCurrentProcess();
    auto size = static_cast<DWORD>(modules.size() * sizeof(HMODULE));
    if (!EnumProcessModules(process, modules.data(), size, &needed)) {
        return std::nullopt;
    }

    if (needed > size) {
        modules.resize(needed / sizeof(HMODULE));
        size = static_cast<DWORD>(modules.size() * sizeof(HMODULE));
        if (!EnumProcessModules(process, modules.data(), size, &needed)) {
            return std::nullopt;
        }
    }
    modules.resize(needed / sizeof(HMODULE));

    for (auto module: modules) {
        auto api = load_python_functions(module);
        if (api) {
            return api;
        }
    }
    return std::nullopt;
#else
    return load_python_functions(RTLD_DEFAULT);
#endif
}

namespace {
/// Information about a Python installation, extracted with find-python.py
struct PythonInfo {
    std::string executable;
    std::string libpython;
    std::string home;
    std::string setup_code;
};
} // namespace

/// Read the full output of `pipe`, removing '\r' from Windows line endings
static std::string read_all(FILE* pipe) {
    auto output = std::string();
    char buffer[4096];
    size_t count = 0;
    while ((count = std::fread(buffer, 1, sizeof(buffer), pipe)) > 0) {
        for (size_t i = 0; i < count; i++) {
            if (buffer[i] != '\r') {
                output.push_back(buffer[i]);
            }
        }
    }
    return output;
}

/// Run the find-python.py script with the given Python executable, adding
/// `arguments` (if any) before the script. Returns `std::nullopt` if the
/// executable could not be run, and throws a `PluginError` if the script
/// reported an error.
static std::optional<PythonInfo> run_find_python(
    const std::string& python,
    const std::string& arguments
) {
    // The script source is given through an environment variable to avoid any
    // issue with quoting or command line length limits
    auto probe = ScopedEnv(
        "METATOMIC_FIND_PYTHON_CODE",
        FIND_PYTHON_CODE
    );
    const auto* code = "import os; exec(os.environ['METATOMIC_FIND_PYTHON_CODE'])";

#ifdef _WIN32
    // cmd.exe removes the outer quotes, so we need to add an additional pair
    auto command = "\"\"" + python + "\" " + arguments + " -c \"" + code + "\" 2>NUL\"";
    auto* pipe = _wpopen(utf8_to_wide(command).c_str(), L"rb");
#else
    auto command = "\"" + python + "\" " + arguments + " -c \"" + code + "\" 2>/dev/null";
    auto* pipe = popen(command.c_str(), "r");
#endif

    if (pipe == nullptr) {
        return std::nullopt;
    }

    auto output = read_all(pipe);
#ifdef _WIN32
    auto status = _pclose(pipe);
#else
    auto status = pclose(pipe);
#endif

    auto lines = std::vector<std::string>();
    size_t start = 0;
    while (lines.size() < 4) {
        auto end = output.find('\n', start);
        if (end == std::string::npos) {
            break;
        }
        lines.push_back(output.substr(start, end - start));
        start = end + 1;
    }

    auto display = arguments.empty() ? python : python + " " + arguments;
    if (!lines.empty() && lines[0].compare(0, PROBE_ERROR.size(), PROBE_ERROR) == 0) {
        throw PluginError(
            "can not use the Python interpreter at '" + display + "': " +
            lines[0].substr(PROBE_ERROR.size())
        );
    }

    if (status != 0 || lines.empty() || lines[0] != PROBE_SUCCESS) {
        return std::nullopt;
    }

    if (lines.size() != 4 || start >= output.size()) {
        throw PluginError("invalid output from the Python probe script for '" + display + "'");
    }

    auto info = PythonInfo();
    info.executable = lines[1];
    info.libpython = lines[2];
    info.home = lines[3];
    info.setup_code = output.substr(start);
    return info;
}

/// Find the Python the user has active, and extract information about it.
static PythonInfo find_user_python() {
    auto explicit_python = get_env("METATOMIC_PYTHON");
    if (explicit_python && !explicit_python->empty()) {
        auto info = run_find_python(*explicit_python, "");
        if (!info) {
            throw PluginError(
                "failed to run the Python interpreter at '" + *explicit_python +
                "' (from METATOMIC_PYTHON)"
            );
        }
        return *info;
    }

    struct Candidate {
        // implicit, so a path can be used directly as a candidate
        Candidate(std::string executable_, std::string arguments_ = std::string()):
            executable(std::move(executable_)),
            arguments(std::move(arguments_))
        {}

        std::string executable;
        std::string arguments;
    };

    // candidates, in order of preference
    auto candidates = std::vector<Candidate>();

    auto virtual_env = get_env("VIRTUAL_ENV");
    if (virtual_env && !virtual_env->empty()) {
#ifdef _WIN32
        candidates.emplace_back(*virtual_env + "\\Scripts\\python.exe");
#else
        candidates.emplace_back(*virtual_env + "/bin/python");
#endif
    }

    auto conda_prefix = get_env("CONDA_PREFIX");
    if (conda_prefix && !conda_prefix->empty()) {
#ifdef _WIN32
        candidates.emplace_back(*conda_prefix + "\\python.exe");
#else
        candidates.emplace_back(*conda_prefix + "/bin/python");
#endif
    }

#ifdef _WIN32
    // Python installs on Windows (python.org, venv, conda) only provide
    // `python.exe`, not `python3.exe`.
    candidates.emplace_back("python");
    // The `py` launcher is installed by python.org, even when Python itself is
    // not added to the PATH.
    candidates.emplace_back("py", "-3");
#else
    candidates.emplace_back("python3");
    candidates.emplace_back("python");
#endif

    for (const auto& candidate: candidates) {
        auto info = run_find_python(candidate.executable, candidate.arguments);
        if (info) {
            return *info;
        }
    }

    throw PluginError(
        "could not find a Python interpreter, please activate a virtual "
        "environment, add python to the PATH or set METATOMIC_PYTHON environment variable"
    );
}

/// Load libpython from `info`, and initialize the interpreter
static void start_python(const PythonInfo& info) {
#ifdef _WIN32
    auto library = LoadLibraryExW(utf8_to_wide(info.libpython).c_str(), nullptr, LOAD_WITH_ALTERED_SEARCH_PATH);
    if (library == nullptr) {
        throw PluginError(
            "failed to load libpython from '" + info.libpython + "' (error " +
            std::to_string(GetLastError()) + ")"
        );
    }
#else
    // RTLD_GLOBAL is required for Python extension modules (numpy, ...), which
    // expect Python symbols to be available globally.
    auto* library = dlopen(info.libpython.c_str(), RTLD_NOW | RTLD_GLOBAL);
    if (library == nullptr) {
        throw PluginError("failed to load libpython from '" + info.libpython + "': " + dlerror());
    }
#endif

    auto api = load_python_functions(library);
    if (!api) {
        throw PluginError("'" + info.libpython + "' does not contain all the expected Python functions");
    }
    PY = *api;

    if (PY.Py_IsInitialized() == 0) {
        {
            auto home = ScopedEnv("PYTHONHOME", info.home);
            // 0 to skip the installation of signal handlers
            PY.Py_InitializeEx(0);
        }

        if (PY.Py_IsInitialized() == 0) {
            throw PluginError("failed to initialize Python from '" + info.libpython + "'");
        }

        auto setup_status = PY.PyRun_SimpleStringFlags(info.setup_code.c_str(), nullptr);

        // release the GIL, so any thread can acquire it with PyGILState_Ensure
        PY.PyEval_SaveThread();

        if (setup_status != 0) {
            // the error was printed by Python
            throw PluginError(
                "failed to setup sys.path for Python at '" + info.executable +
                "', see the error above"
            );
        }
    }
}

/// Make sure Python is loaded and initialized. This is safe to call multiple
/// times and from multiple threads.
static void ensure_python() {
    static std::mutex MUTEX;
    static bool PYTHON_READY = false;

    auto lock = std::lock_guard<std::mutex>(MUTEX);
    if (PYTHON_READY) {
        return;
    }

    auto api = find_python_in_process();
    if (api && (api->Py_IsInitialized() != 0)) {
        // Python is already running (e.g. the engine is written in Python),
        // use it as-is
        PY = *api;
    } else {
        start_python(find_user_python());
    }

    PYTHON_READY = true;
}

