namespace {
/// RAII wrapper around an owned reference to a Python object. This must only
/// be created and destroyed while holding the GIL.
class PyRef {
public:
    PyRef() = default;

    /// Take ownership of `object`, throwing `PythonError` if it is NULL
    static PyRef check(PyObject* object) {
        if (object == nullptr) {
            throw PythonError{};
        }
        return PyRef(object);
    }

    ~PyRef() {
        if (object_ != nullptr) {
            PY.Py_DecRef(object_);
        }
    }

    PyRef(const PyRef&) = delete;
    PyRef& operator=(const PyRef&) = delete;

    PyRef(PyRef&& other) noexcept: object_(std::exchange(other.object_, nullptr)) {}
    PyRef& operator=(PyRef&& other) noexcept {
        std::swap(object_, other.object_);
        return *this;
    }

    PyObject* get() const {
        return object_;
    }

private:
    explicit PyRef(PyObject* object): object_(object) {}

    PyObject* object_ = nullptr;
};

/// RAII guard holding the GIL
class GilGuard {
public:
    GilGuard(): state_(PY.PyGILState_Ensure()) {}
    ~GilGuard() {
        PY.PyGILState_Release(state_);
    }

    GilGuard(const GilGuard&) = delete;
    GilGuard& operator=(const GilGuard&) = delete;

private:
    PyGILState_STATE state_;
};
} // namespace


