namespace {
// We only use pointers to Python objects, so we don't need the full definition
struct PyObject;
using Py_ssize_t = std::ptrdiff_t;
// `PyGILState_STATE` is an enum
using PyGILState_STATE = int;

/// All the functions we need from libpython, they will be dynamically loaded at
/// runtime to avoid linking to a specific Python version.
struct PythonApi {
    int (*Py_IsInitialized)() = nullptr;
    void (*Py_InitializeEx)(int) = nullptr;
    void* (*PyEval_SaveThread)() = nullptr;
    PyGILState_STATE (*PyGILState_Ensure)() = nullptr;
    void (*PyGILState_Release)(PyGILState_STATE) = nullptr;
    int (*PyRun_SimpleStringFlags)(const char*, void*) = nullptr;

    PyObject* (*PyImport_ImportModule)(const char*) = nullptr;
    PyObject* (*PyObject_CallMethod)(PyObject*, const char*, const char*, ...) = nullptr;
    PyObject* (*PyObject_GetAttrString)(PyObject*, const char*) = nullptr;
    PyObject* (*PyDict_GetItemString)(PyObject*, const char*) = nullptr;
    int (*PyObject_IsInstance)(PyObject*, PyObject*) = nullptr;
    void* (*PyLong_AsVoidPtr)(PyObject*) = nullptr;
    void (*Py_IncRef)(PyObject*) = nullptr;
    void (*Py_DecRef)(PyObject*) = nullptr;

    PyObject* (*PyErr_Occurred)() = nullptr;
    void (*PyErr_Clear)() = nullptr;
    PyObject* (*PyObject_Str)(PyObject*) = nullptr;
    const char* (*PyUnicode_AsUTF8AndSize)(PyObject*, Py_ssize_t*) = nullptr;
    // only available in Python >= 3.12
    PyObject* (*PyErr_GetRaisedException)() = nullptr;
    // used for Python < 3.12
    void (*PyErr_Fetch)(PyObject**, PyObject**, PyObject**) = nullptr;
    void (*PyErr_NormalizeException)(PyObject**, PyObject**, PyObject**) = nullptr;
    int (*PyException_SetTraceback)(PyObject*, PyObject*) = nullptr;
};
} // namespace

static PythonApi PY;

template <typename T>
static bool load_symbol(library_t library, const char* name, T& function) {
    function = reinterpret_cast<T>(get_symbol(library, name));
    return function != nullptr;
}

/// Try to load all the functions we need from `library`, returning
/// `std::nullopt` if any of them is missing.
static std::optional<PythonApi> load_python_functions(library_t library) {
    auto api = PythonApi();

    #define LOAD(name) if (!load_symbol(library, #name, api.name)) { return std::nullopt; }

    LOAD(Py_IsInitialized);
    LOAD(Py_InitializeEx);
    LOAD(PyEval_SaveThread);
    LOAD(PyGILState_Ensure);
    LOAD(PyGILState_Release);
    LOAD(PyRun_SimpleStringFlags);
    LOAD(PyImport_ImportModule);
    LOAD(PyObject_CallMethod);
    LOAD(PyObject_GetAttrString);
    LOAD(PyDict_GetItemString);
    LOAD(PyObject_IsInstance);
    LOAD(PyLong_AsVoidPtr);
    LOAD(Py_IncRef);
    LOAD(Py_DecRef);
    LOAD(PyErr_Occurred);
    LOAD(PyErr_Clear);
    LOAD(PyObject_Str);
    LOAD(PyUnicode_AsUTF8AndSize);

    if (!load_symbol(library, "PyErr_GetRaisedException", api.PyErr_GetRaisedException)) {
        LOAD(PyErr_Fetch);
        LOAD(PyErr_NormalizeException);
        LOAD(PyException_SetTraceback);
    }

    #undef LOAD

    return api;
}

