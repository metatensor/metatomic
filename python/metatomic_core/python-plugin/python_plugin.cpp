#ifdef _WIN32
using library_t = HMODULE;

static void* get_symbol(library_t library, const char* name) {
    return reinterpret_cast<void*>(GetProcAddress(library, name));
}

static std::wstring utf8_to_wide(const std::string& string) {
    if (string.empty()) {
        return std::wstring();
    }

    auto size = MultiByteToWideChar(CP_UTF8, 0, string.data(), static_cast<int>(string.size()), nullptr, 0);
    auto result = std::wstring(static_cast<size_t>(size), L'\0');
    MultiByteToWideChar(CP_UTF8, 0, string.data(), static_cast<int>(string.size()), &result[0], size);
    return result;
}

static std::string wide_to_utf8(const wchar_t* string) {
    auto size = WideCharToMultiByte(CP_UTF8, 0, string, -1, nullptr, 0, nullptr, nullptr);
    if (size <= 1) {
        return std::string();
    }
    // `size` includes the NULL terminator
    auto result = std::string(static_cast<size_t>(size - 1), '\0');
    WideCharToMultiByte(CP_UTF8, 0, string, -1, &result[0], size, nullptr, nullptr);
    return result;
}
#else
using library_t = void*;

static void* get_symbol(library_t library, const char* name) {
    return dlsym(library, name);
}
#endif

/// Get the value of an environment variable, or `std::nullopt` if the variable
/// is not set
static std::optional<std::string> get_env(const char* name) {
#ifdef _WIN32
    const auto* value = _wgetenv(utf8_to_wide(name).c_str());
    if (value == nullptr) {
        return std::nullopt;
    }
    return wide_to_utf8(value);
#else
    const auto* value = std::getenv(name);
    if (value == nullptr) {
        return std::nullopt;
    }
    return std::string(value);
#endif
}

/// Set (or unset if `value` is `std::nullopt`) an environment variable
static void set_env(const char* name, const std::optional<std::string>& value) {
#ifdef _WIN32
    auto wide_name = utf8_to_wide(name);
    auto wide_value = utf8_to_wide(value.value_or(""));
    // setting an empty value removes the variable. We update both the C
    // runtime environment (used by Python and `_wpopen`) and the process
    // environment.
    _wputenv_s(wide_name.c_str(), wide_value.c_str());
    SetEnvironmentVariableW(wide_name.c_str(), value ? wide_value.c_str() : nullptr);
#else
    if (value) {
        setenv(name, value->c_str(), 1);
    } else {
        unsetenv(name);
    }
#endif
}

namespace {
/// Set an environment variable for the lifetime of this object, restoring the
/// previous value when it is destroyed.
class ScopedEnv {
public:
    ScopedEnv(const char* name, const std::string& value): name_(name), old_value_(get_env(name)) {
        set_env(name_, value);
    }

    ~ScopedEnv() {
        set_env(name_, old_value_);
    }

    ScopedEnv(const ScopedEnv&) = delete;
    ScopedEnv& operator=(const ScopedEnv&) = delete;

private:
    const char* name_;
    std::optional<std::string> old_value_;
};
} // namespace


