namespace {
/// Error in the plugin itself, reported with `MTA_INVALID_PARAMETER_ERROR`
class PluginError: public std::runtime_error {
public:
    using std::runtime_error::runtime_error;
};

/// Marker exception, thrown when a Python function failed and a Python
/// exception is set. This must only be thrown and caught with the GIL held.
struct PythonError {};
} // namespace

/// Data deleter for `mta_set_last_error`, releasing a Python exception
static void python_exception_deleter(void* exception) {
    auto state = PY.PyGILState_Ensure();
    PY.Py_DecRef(static_cast<PyObject*>(exception));
    PY.PyGILState_Release(state);
}

/// Move the current Python exception into the last metatomic error. This must
/// be called with the GIL held, and a Python exception set.
static mta_status_t set_error_from_python() {
    PyObject* exception = nullptr;
    if (PY.PyErr_GetRaisedException != nullptr) {
        exception = PY.PyErr_GetRaisedException();
    } else {
        PyObject* type = nullptr;
        PyObject* traceback = nullptr;
        PY.PyErr_Fetch(&type, &exception, &traceback);
        PY.PyErr_NormalizeException(&type, &exception, &traceback);
        if (exception != nullptr && traceback != nullptr) {
            PY.PyException_SetTraceback(exception, traceback);
        }
        if (type != nullptr) {
            PY.Py_DecRef(type);
        }
        if (traceback != nullptr) {
            PY.Py_DecRef(traceback);
        }
    }

    if (exception == nullptr) {
        mta_set_last_error("unknown Python error", PLUGIN_NAME, nullptr, nullptr);
        return MTA_MODEL_ERROR;
    }

    // Get `str(object)` as a C++ string, or an empty string on error
    auto to_string = [](PyObject* object) {
        auto result = std::string();
        if (object == nullptr) {
            return result;
        }

        auto* string = PY.PyObject_Str(object);
        if (string != nullptr) {
            const auto* utf8 = PY.PyUnicode_AsUTF8AndSize(string, nullptr);
            if (utf8 != nullptr) {
                result = utf8;
            }
            PY.Py_DecRef(string);
        } else {
            result = "<unprintable Python exception>";
        }
        // clear any error from `str(object)`
        PY.PyErr_Clear();
        return result;
    };


    auto class_name = std::string();
    auto* klass = PY.PyObject_GetAttrString(exception, "__class__");
    if (klass != nullptr) {
        auto* name = PY.PyObject_GetAttrString(klass, "__name__");
        class_name = to_string(name);
        if (name != nullptr) {
            PY.Py_DecRef(name);
        }
        PY.Py_DecRef(klass);
    }
    PY.PyErr_Clear();

    auto message = to_string(exception);
    if (message.empty()) {
        message = class_name.empty() ? "<Python exception>" : class_name;
    } else if (!class_name.empty()) {
        message = class_name + ": " + message;
    }

    // the reference to `exception` is transferred to metatomic, and will be
    // released by `python_exception_deleter`
    mta_set_last_error(message.c_str(), PYTHON_EXCEPTION_ORIGIN, exception, python_exception_deleter);
    return MTA_MODEL_ERROR;
}

